/* Interactive fretboard tools: scale/arpeggio finder and note-name trainer.
   Data comes from data/theory.js (generated by the Python engine). */
(function () {
  'use strict';
  const T = window.JG_THEORY;
  if (!T) return;
  const TUNING = [40, 45, 50, 55, 59, 64]; // string 6..1
  const NAMES_FLAT = ['C', 'Db', 'D', 'Eb', 'E', 'F', 'Gb', 'G', 'Ab', 'A', 'Bb', 'B'];
  const NAMES_SHARP = ['C', 'C#', 'D', 'D#', 'E', 'F', 'F#', 'G', 'G#', 'A', 'A#', 'B'];
  function midiAt(string, fret) { return TUNING[6 - string] + fret; }
  function esc(s) { return String(s).replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c])); }

  /** dots: [{s, f, label, root}] -> svg string (mirrors sitegen/diagrams.fretboard_svg) */
  function fretboardSVG(dots, lo, hi, title, opts) {
    opts = opts || {};
    const fw = 34, sh = 16, x0 = lo === 0 ? 30 : 24, y0 = title ? 30 : 14;
    const first = lo > 0 ? lo : 1;
    const cells = hi - first + 1;
    const w = x0 + fw * cells + 12, h = y0 + sh * 5 + 26;
    let s = '<svg class="fretboard" viewBox="0 0 ' + w + ' ' + h + '" width="' + w + '" height="' + h + '" role="img">';
    if (title) s += '<text class="fb-title" x="' + x0 + '" y="14">' + esc(title) + '</text>';
    for (let i = 0; i <= cells; i++) {
      const x = x0 + i * fw;
      s += '<line class="' + (lo === 0 && i === 0 ? 'fb-nut' : 'fb-fret') + '" x1="' + x + '" y1="' + y0 + '" x2="' + x + '" y2="' + (y0 + sh * 5) + '"/>';
    }
    for (let i = 0; i < 6; i++) {
      const y = y0 + i * sh;
      s += '<line class="fb-string" x1="' + x0 + '" y1="' + y + '" x2="' + (x0 + fw * cells) + '" y2="' + y + '" style="stroke-width:' + (0.8 + i * 0.25).toFixed(2) + '"/>';
    }
    [3, 5, 7, 9, 12, 15, 17, 19, 21].forEach(f => {
      if (f >= first && f <= hi) {
        const x = x0 + (f - first) * fw + fw / 2;
        if (f === 12) { s += '<circle class="fb-inlay" cx="' + x + '" cy="' + (y0 + sh * 1.5) + '" r="3"/><circle class="fb-inlay" cx="' + x + '" cy="' + (y0 + sh * 3.5) + '" r="3"/>'; }
        else s += '<circle class="fb-inlay" cx="' + x + '" cy="' + (y0 + sh * 2.5) + '" r="3"/>';
      }
    });
    for (let f = first; f <= hi; f++) {
      s += '<text class="fb-num" x="' + (x0 + (f - first) * fw + fw / 2) + '" y="' + (y0 + sh * 5 + 16) + '" text-anchor="middle">' + f + '</text>';
    }
    dots.forEach(d => {
      const y = y0 + (d.s - 1) * sh;
      const x = d.f === 0 ? x0 - 12 : x0 + (d.f - first) * fw + fw / 2;
      const extra = d.cls ? ' ' + d.cls : '';
      s += '<circle class="fb-dot' + (d.root ? ' fb-root' : '') + extra + '" cx="' + x + '" cy="' + y + '" r="7" data-s="' + d.s + '" data-f="' + d.f + '"/>';
      if (d.label) s += '<text class="fb-label" x="' + x + '" y="' + (y + 2.6) + '" text-anchor="middle" style="pointer-events:none">' + esc(d.label) + '</text>';
    });
    s += '</svg>';
    return s;
  }
  window.JGFretboard = { fretboardSVG, midiAt };

  // ---------------- scale finder ----------------
  const finder = document.getElementById('scale-finder');
  if (finder) {
    const rootSel = finder.querySelector('[name=root]');
    const kindSel = finder.querySelector('[name=kind]');
    const scaleSel = finder.querySelector('[name=scale]');
    const chordSel = finder.querySelector('[name=chord]');
    const labelSel = finder.querySelector('[name=label]');
    const loInp = finder.querySelector('[name=lo]');
    const hiInp = finder.querySelector('[name=hi]');
    const out = finder.querySelector('.fb-wrap');
    const info = finder.querySelector('.finder-info');
    T.roots.forEach(r => rootSel.add(new Option(r, r)));
    Object.keys(T.scales).forEach(k => scaleSel.add(new Option(T.scales[k].display, k)));
    Object.keys(T.chordTypes).forEach(k => chordSel.add(new Option(k === 'maj' ? 'major triad' : T.chordTypes[k].display, k)));
    function render() {
      const root = rootSel.value;
      const kind = kindSel.value;
      scaleSel.parentElement.hidden = kind !== 'scale';
      chordSel.parentElement.hidden = kind !== 'chord';
      const lo = Math.max(0, Number(loInp.value)), hi = Math.min(22, Math.max(lo + 1, Number(hiInp.value)));
      let entry, title;
      if (kind === 'scale') { entry = T.scaleNotes[root][scaleSel.value]; title = root + ' ' + T.scales[scaleSel.value].display; }
      else { entry = T.chordNotes[root][chordSel.value]; title = root + T.chordTypes[chordSel.value].display; }
      const pcs = entry.pcs, labels = entry.labels, names = entry.notes;
      const dots = [];
      for (let st = 1; st <= 6; st++) for (let f = lo; f <= hi; f++) {
        const pc = midiAt(st, f) % 12; const i = pcs.indexOf(pc);
        if (i >= 0) dots.push({ s: st, f, label: labelSel.value === 'degree' ? labels[i] : names[i], root: i === 0 });
      }
      out.innerHTML = fretboardSVG(dots, lo, hi, title);
      info.innerHTML = '<b>Notes:</b> ' + names.join(' – ') + ' &nbsp; <b>Formula:</b> ' + labels.join(' ') +
        (kind === 'scale' && T.scales[scaleSel.value].chords.length ? '<br><b>Chords this scale fits:</b> ' + T.scales[scaleSel.value].chords.join(', ') : '');
      const playBtn = finder.querySelector('.btn-play-scale');
      if (playBtn) playBtn.onclick = () => {
        const base = 48 + ((pcs[0] - 0 + 12) % 12);
        const seq = pcs.map((pc, i) => base + ((pc - pcs[0] + 12) % 12) + (i > 0 && ((pc - pcs[0] + 12) % 12) === 0 ? 12 : 0));
        if (kind === 'scale') seq.push(base + 12);
        if (window.JGAudio) window.JGAudio.playNotes(seq, { mode: kind === 'scale' ? 'melodic' : 'both', dur: 0.45 });
      };
    }
    [rootSel, kindSel, scaleSel, chordSel, labelSel, loInp, hiInp].forEach(el => el.addEventListener('change', render));
    render();
  }

  // ---------------- note trainer ----------------
  const trainer = document.getElementById('note-trainer');
  if (trainer) {
    const board = trainer.querySelector('.fb-wrap');
    const answers = trainer.querySelector('.big-answer');
    const stats = trainer.querySelector('.stat-row');
    const stringsSel = trainer.querySelector('[name=strings]');
    const maxFret = trainer.querySelector('[name=maxfret]');
    let correct = 0, total = 0, streak = 0, cur = null;
    function ask() {
      const allowed = stringsSel.value === 'all' ? [1, 2, 3, 4, 5, 6] : stringsSel.value.split('').map(Number);
      const s = allowed[Math.floor(Math.random() * allowed.length)];
      const f = Math.floor(Math.random() * (Number(maxFret.value) + 1));
      cur = { s, f, pc: midiAt(s, f) % 12 };
      board.innerHTML = fretboardSVG([{ s, f, label: '?', root: true }], 0, Number(maxFret.value), 'Which note is this?');
      const names = NAMES_FLAT.map((n, i) => (NAMES_SHARP[i] !== n ? n + ' / ' + NAMES_SHARP[i] : n));
      answers.innerHTML = names.map((n, i) => '<button type="button" data-pc="' + i + '">' + n + '</button>').join('');
    }
    answers.addEventListener('click', ev => {
      const b = ev.target.closest('button'); if (!b || !cur) return;
      const pc = Number(b.dataset.pc); total++;
      if (pc === cur.pc) { correct++; streak++; b.classList.add('correct'); }
      else { streak = 0; b.classList.add('wrong'); answers.querySelector('[data-pc="' + cur.pc + '"]').classList.add('correct'); }
      if (window.JGAudio) window.JGAudio.playNotes([midiAt(cur.s, cur.f)], { dur: 0.5 });
      stats.innerHTML = '<span>Correct: <b>' + correct + '</b> / ' + total + '</span><span>Streak: <b>' + streak + '</b></span>';
      answers.querySelectorAll('button').forEach(x => { x.disabled = true; });
      setTimeout(ask, 900);
    });
    trainer.querySelector('.btn-start').addEventListener('click', () => { correct = 0; total = 0; streak = 0; ask(); });
  }

  // ---------------- find-the-note trainer ----------------
  const finderGame = document.getElementById('find-note');
  if (finderGame) {
    const board = finderGame.querySelector('.fb-wrap');
    const prompt = finderGame.querySelector('.prompt');
    const stats = finderGame.querySelector('.stat-row');
    let target = null, found = 0, total = 0, remaining = [];
    function ask() {
      const pc = Math.floor(Math.random() * 12);
      target = pc;
      remaining = [];
      const dots = [];
      for (let s = 1; s <= 6; s++) for (let f = 0; f <= 12; f++) {
        dots.push({ s, f, label: '', root: false, cls: 'fb-blank' });
        if (midiAt(s, f) % 12 === pc) remaining.push(s + ':' + f);
      }
      total = remaining.length; found = 0;
      prompt.innerHTML = 'Click every <b>' + NAMES_FLAT[pc] + (NAMES_SHARP[pc] !== NAMES_FLAT[pc] ? ' / ' + NAMES_SHARP[pc] : '') + '</b> between the nut and fret 12 (' + total + ' positions).';
      board.innerHTML = fretboardSVG(dots, 0, 12, '');
      board.querySelectorAll('.fb-blank').forEach(c => { c.style.fill = 'transparent'; c.style.cursor = 'pointer'; });
      stats.innerHTML = '';
    }
    board.addEventListener('click', ev => {
      const c = ev.target.closest('circle'); if (!c || target === null) return;
      const s = Number(c.dataset.s), f = Number(c.dataset.f);
      const key = s + ':' + f;
      if (midiAt(s, f) % 12 === target) {
        if (remaining.includes(key)) { remaining = remaining.filter(k => k !== key); found++; }
        c.style.fill = 'var(--ok)';
        if (window.JGAudio) window.JGAudio.playNotes([midiAt(s, f)], { dur: 0.4 });
      } else {
        c.style.fill = 'var(--accent)';
        setTimeout(() => { c.style.fill = 'transparent'; }, 500);
      }
      stats.innerHTML = '<span>Found <b>' + found + '</b> / ' + total + '</span>';
      if (!remaining.length) { stats.innerHTML += '<span><b>All found!</b></span>'; setTimeout(ask, 1200); }
    });
    finderGame.querySelector('.btn-start').addEventListener('click', ask);
  }
})();
